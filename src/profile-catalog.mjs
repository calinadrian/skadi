// Skadi's pre-made launch profiles, tuned and measured on a 16 GB card
// (RX 9070 XT). They live in code rather than config/profiles.json so they ship
// with every release and cannot be edited in place: config.mjs overlays them on
// whatever the user has saved, and never writes them back. To change one, the
// user duplicates it -- the copy is an ordinary profile.
//
// A `serverExe` of "@name" is an engine, not a path: config.mjs resolves it
// against the `engines` table in profiles.json, and falls back to the main
// `serverExe` when the machine has no such engine registered.
//
// `info` is what the catalog page shows: perplexity (lower is better), measured
// decode speed, and a plain-language note. It is not passed to llama-server.
// An entry is matched to a model by its `model` file name, which is also how the
// model browser knows to badge a download as "has a Skadi profile".

