export const isCatalogId = (id) => Object.hasOwn(PROFILE_CATALOG, id);

/** Catalog profiles whose model file is `fileName` (case-insensitive), recommended first. */
export function catalogFor(fileName) {
  const wanted = String(fileName || '').toLowerCase();
  return Object.entries(PROFILE_CATALOG)
    .filter(([, p]) => String(p.model || '').toLowerCase() === wanted)
    .map(([id, p]) => ({ id, label: p.label, tier: p.info?.tier }));
}
